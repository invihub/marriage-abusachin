"""
QR codes for the venues, printed on the downloadable RSVP ticket.

  Haldi & Sangeet and the Wedding share one venue (Thoothukudi): one QR code.
  The Reception (Chennai) has its own.

Writes:
  js/venue-qr.js           the QR patterns the ticket draws (js/rsvp-ticket.js)
  images/qr/<venue>.svg    the same QR codes as pictures (for print, sharing)

Run again only if a venue's Google Maps link changes (edit VENUES below):
  pip install segno
  python scripts/build-qr.py
Nothing here runs on the website; it only needs the files this writes.
"""

import json
import os

import segno

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# key: used by js/rsvp-ticket.js (ceremony -> venue is set there, RT_VENUES)
VENUES = {
    'thoothukudi': {
        'name': 'AVM Kamalavel Mahal, Thoothukudi',
        'url': 'https://maps.app.goo.gl/9LsKEyBVSDDpFLWo8',
    },
    'chennai': {
        'name': 'Madras Race Club, Guindy, Chennai',
        'url': 'https://maps.app.goo.gl/KuNMGB7UNr8dQDk16',
    },
}


def main():
    data = {}
    os.makedirs(os.path.join(ROOT, 'images', 'qr'), exist_ok=True)
    for key, venue in VENUES.items():
        # error correction M: still scans if a little of it is smudged or blurred
        qr = segno.make_qr(venue['url'], error='m', boost_error=False)
        rows = [''.join('1' if dark else '0' for dark in row) for row in qr.matrix]
        data[key] = {'name': venue['name'], 'url': venue['url'], 'rows': rows}
        qr.save(os.path.join(ROOT, 'images', 'qr', f'{key}.svg'), scale=10, border=4,
                dark='#3B2416', light='#FFFFFF', xmldecl=False, svgns=True)
        print(f'{key}: version {qr.version}, {len(rows)}x{len(rows)} modules, {venue["url"]}')

    js = (
        '// Generated by scripts/build-qr.py: QR codes for the venues\' Google Maps\n'
        '// links, drawn on the downloadable RSVP ticket (js/rsvp-ticket.js).\n'
        '// Don\'t edit by hand; change the links in the script and run it again.\n'
        '// rows: one string per row of the code, 1 = dark square.\n'
        f'window.VENUE_QR = {json.dumps(data, indent=2)};\n'
    )
    with open(os.path.join(ROOT, 'js', 'venue-qr.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)


if __name__ == '__main__':
    main()
