// Generates js/config.js (gitignored) from environment variables.
// Locally it reads .env; in GitHub Actions it reads repository secrets.
//   node scripts/build-config.mjs
// Only the URL and the publishable key are written: the secret key must
// never reach the browser.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const envFile = path.join(root, '.env');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    // real environment variables win over .env
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const url = process.env.SUPABASE_URL;
const publishableKey = process.env.SUPABASE_PUBLISHABLE_KEY;
const schema = process.env.SUPABASE_SCHEMA;

if (!url || !publishableKey || !schema) {
  console.error('Missing SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY or SUPABASE_SCHEMA (set them in .env or the environment).');
  process.exit(1);
}
if (!/^[a-z_][a-z0-9_]*$/.test(schema)) {
  console.error('SUPABASE_SCHEMA must be lowercase letters, digits and underscores (e.g. abu_sachin).');
  process.exit(1);
}
if (!publishableKey.startsWith('sb_publishable_')) {
  console.error('SUPABASE_PUBLISHABLE_KEY must be the publishable key (sb_publishable_...), never the secret key.');
  process.exit(1);
}

const config = { supabaseUrl: url.replace(/\/+$/, ''), supabasePublishableKey: publishableKey, supabaseSchema: schema };
writeFileSync(
  path.join(root, 'js', 'config.js'),
  `// Generated by scripts/build-config.mjs from environment variables. Do not edit or commit.\n` +
  `window.SITE_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);
console.log('Wrote js/config.js');
