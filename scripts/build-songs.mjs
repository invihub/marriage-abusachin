// Generates js/songs.js (gitignored): the soundtrack playlist, read from the
// files in songs/. The deploy workflow runs it; locally run it after adding,
// removing or renaming a song:
//   node scripts/build-songs.mjs
// Songs play in file-name order, so number them: 01-Theera-Ulaa.mp3,
// 02-Kaara-Aattakkaara.mp3, ... The player shows the name without the number
// (dashes become spaces): "Theera Ulaa".
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'songs');
const AUDIO = /\.(mp3|m4a|aac|ogg|oga|opus|wav|webm)$/i;

const files = existsSync(dir)
  ? readdirSync(dir).filter((f) => AUDIO.test(f))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }))
  : [];

writeFileSync(
  path.join(root, 'js', 'songs.js'),
  `// Generated by scripts/build-songs.mjs from the files in songs/. Do not edit.\n` +
  `window.SONG_FILES = ${JSON.stringify(files, null, 2)};\n`
);
console.log(`Wrote js/songs.js (${files.length} song${files.length === 1 ? '' : 's'})`);
files.forEach((f) => console.log('  ' + f));
